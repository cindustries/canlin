#!/bin/sh
# Regenerate the TLS test fixtures of t/net (HTTP transport spec §9). Test material only:
# the keys are public, nothing here may ever be trusted outside the loopback tests.
#
#   ca.pem                        test CA (P-256), valid 2019-01-01 .. 2060-01-01
#   localhost-ec.pem / .key       leaf for localhost, 127.0.0.1, ::1 (P-256)
#   localhost-rsa.pem / .key      same names, RSA 2048
#   wrong-host.pem / .key         leaf for wrong.example only
#   expired.pem / .key            localhost leaf, valid 2020-01-01 .. 2021-01-01
#   self-signed.pem / .key        localhost, self-signed (not issued by the test CA)
#   other-ca.pem, other-leaf.pem / .key   a localhost leaf from an untrusted CA
#   certs.h                       every PEM above as C strings (the tests embed them,
#                                 so they also run where t/ is not on disk, e.g. QEMU)
#
# Leaves are valid 2025-01-01 .. 2045-01-01. Fixed dates keep the tests independent of
# the real clock: the tests use a fake wall clock (2030-06-01 by default).
# Usage: sh t/net/fixtures/mkcerts.sh   (needs OpenSSL >= 3.4 for -not_before/-not_after)
set -eu
cd "$(dirname "$0")"

NB=20250101000000Z
NA=20450101000000Z
SAN="subjectAltName=DNS:localhost,IP:127.0.0.1,IP:::1"
LEAFEXT="basicConstraints=critical,CA:FALSE
keyUsage=critical,digitalSignature,keyEncipherment
extendedKeyUsage=serverAuth"

ec_key() { openssl genpkey -algorithm EC -pkeyopt ec_paramgen_curve:P-256 -out "$1" 2>/dev/null; }

mk_ca() { # name cn
    ec_key "$1.key"
    openssl req -x509 -new -key "$1.key" -subj "/CN=$2" -sha256 \
        -not_before 20190101000000Z -not_after 20600101000000Z \
        -addext "basicConstraints=critical,CA:TRUE" \
        -addext "keyUsage=critical,keyCertSign,cRLSign" \
        -addext "subjectKeyIdentifier=hash" -out "$1.pem"
}

mk_leaf() { # name keyfile ca san notbefore notafter
    printf '%s\n%s\n' "$LEAFEXT" "$4" > ext.tmp
    openssl req -new -key "$2" -subj "/CN=$1" -out csr.tmp
    openssl x509 -req -in csr.tmp -CA "$3.pem" -CAkey "$3.key" -set_serial "0x$(openssl rand -hex 8)" \
        -sha256 -not_before "$5" -not_after "$6" -extfile ext.tmp -out "$1.pem"
    rm -f csr.tmp ext.tmp
}

mk_ca ca "CanLin Test CA"
mk_ca other-ca "CanLin Untrusted Test CA"

ec_key localhost-ec.key
mk_leaf localhost-ec localhost-ec.key ca "$SAN" $NB $NA
openssl genpkey -algorithm RSA -pkeyopt rsa_keygen_bits:2048 -out localhost-rsa.key 2>/dev/null
mk_leaf localhost-rsa localhost-rsa.key ca "$SAN" $NB $NA
ec_key wrong-host.key
mk_leaf wrong-host wrong-host.key ca "subjectAltName=DNS:wrong.example" $NB $NA
ec_key expired.key
mk_leaf expired expired.key ca "$SAN" 20200101000000Z 20210101000000Z
ec_key other-leaf.key
mk_leaf other-leaf other-leaf.key other-ca "$SAN" $NB $NA
ec_key self-signed.key
openssl req -x509 -new -key self-signed.key -subj "/CN=localhost" -sha256 \
    -not_before $NB -not_after $NA -addext "$SAN" -out self-signed.pem
rm -f ca.key other-ca.key ca.srl other-ca.srl

# certs.h: C string per file, name derived from the file name.
{
    echo "/* Generated by t/net/fixtures/mkcerts.sh - do not edit. Test-only keys. */"
    for f in ca.pem other-ca.pem localhost-ec.pem localhost-ec.key localhost-rsa.pem \
             localhost-rsa.key wrong-host.pem wrong-host.key expired.pem expired.key \
             self-signed.pem self-signed.key other-leaf.pem other-leaf.key; do
        v=$(echo "$f" | tr '.-' '__')
        echo "static const char fx_$v[] ="
        sed 's/^/    "/; s/$/\\n"/' "$f"
        echo "    ;"
    done
} > certs.h
echo "fixtures written to $(pwd)"
