#!/usr/bin/env python3
"""Derive CanLin's built-in font (canlin#22, UI spec §6.3).

Subsets the vendored Inter Regular (third_party/fonts/inter) to a Latin set and
writes src/render/font_builtin.c: the subset TTF as a byte array plus the Nuklear
glyph range table baked from it. Ranges and subset come from one list, so every
baked codepoint exists in the font. Run from the repository root:

    python3 -m venv /tmp/v && /tmp/v/bin/pip install fonttools==4.65.0
    /tmp/v/bin/python tools/mkfont.py

The output is committed (fontTools is not a build dependency); rerunning with the
pinned fontTools must reproduce it byte for byte. Inter is under the SIL OFL 1.1 and
declares no Reserved Font Name, so the subset (a Modified Version under the OFL) may
keep the name "Inter"; it keeps every name-table string (copyright, trademark notice,
licence). Hinting is dropped (stb_truetype ignores it), as are OpenType layout tables
(Nuklear does no shaping or kerning).
"""
import io
import sys

import fontTools
from fontTools import subset
from fontTools.ttLib import TTFont

FONTTOOLS = "4.65.0"
SRC = "third_party/fonts/inter/Inter-Regular.ttf"
OUT = "src/render/font_builtin.c"

# (first, last) inclusive. Keep sorted, non-overlapping. Inter 4.1 has no glyph for
# U+00AD SOFT HYPHEN or U+0149 (deprecated n preceded by apostrophe); both are left
# out and render as the U+25A1 fallback box.
RANGES = [
    (0x0020, 0x007E),  # ASCII
    (0x00A0, 0x00AC),  # Latin-1 Supplement (without U+00AD)
    (0x00AE, 0x00FF),
    (0x0100, 0x0148),  # Latin Extended-A (without U+0149)
    (0x014A, 0x017F),
    (0x2013, 0x2014),  # en/em dash
    (0x2018, 0x201A),  # single quotes
    (0x201C, 0x201E),  # double quotes
    (0x2020, 0x2022),  # dagger, double dagger, bullet
    (0x2026, 0x2026),  # ellipsis
    (0x2030, 0x2030),  # per mille
    (0x2039, 0x203A),  # single guillemets
    (0x20AC, 0x20AC),  # euro
    (0x2122, 0x2122),  # trade mark
    (0x2190, 0x2193),  # arrows left/up/right/down
    (0x25A1, 0x25A1),  # white square: replacement box for missing glyphs
    (0x25B2, 0x25B2),  # up triangle
    (0x25B6, 0x25B6),  # right triangle
    (0x25BC, 0x25BC),  # down triangle
    (0x25C0, 0x25C0),  # left triangle
]


def main():
    if fontTools.version != FONTTOOLS:
        sys.exit("fontTools %s required, have %s" % (FONTTOOLS, fontTools.version))
    cps = [c for a, b in RANGES for c in range(a, b + 1)]
    # recalcTimestamp=False: otherwise save() stamps head.modified with the current
    # time (subset.Options.recalc_timestamp only governs pyftsubset's own loading).
    font = TTFont(SRC, recalcTimestamp=False)
    cmap = font.getBestCmap()
    missing = [hex(c) for c in cps if c not in cmap]
    if missing:
        sys.exit("not in %s: %s" % (SRC, " ".join(missing)))

    opt = subset.Options()
    opt.hinting = False
    opt.layout_features = []
    opt.name_IDs = ["*"]
    opt.name_languages = ["*"]
    opt.name_legacy = True
    opt.notdef_outline = True
    opt.glyph_names = False
    opt.recalc_timestamp = False
    sub = subset.Subsetter(opt)
    sub.populate(unicodes=cps)
    sub.subset(font)
    buf = io.BytesIO()
    font.save(buf)
    data = buf.getvalue()

    out = []
    out.append("/* GENERATED by tools/mkfont.py from %s -- do not edit.\n" % SRC)
    out.append(" *\n")
    out.append(" * Inter 4.1 Regular, Latin subset (%d codepoints, %d bytes), fontTools %s.\n"
               % (len(cps), len(data), FONTTOOLS))
    out.append(" * Copyright 2016 The Inter Project Authors (https://github.com/rsms/inter),\n")
    out.append(" * licensed under the SIL Open Font License, Version 1.1. Full text:\n")
    out.append(" * third_party/fonts/inter/LICENSE, which must accompany every distributed\n")
    out.append(" * copy. */\n")
    out.append('#include "font_builtin.h"\n\n')
    out.append("const nk_rune canlin_font_builtin_ranges[] = {\n")
    for a, b in RANGES:
        out.append("    0x%04X, 0x%04X,\n" % (a, b))
    out.append("    0\n};\n\n")
    out.append("const unsigned long canlin_font_builtin_ttf_size = %dUL;\n\n" % len(data))
    out.append("const unsigned char canlin_font_builtin_ttf[%d] = {\n" % len(data))
    for i in range(0, len(data), 16):
        out.append("    " + ",".join("%d" % v for v in data[i:i + 16]) + ",\n")
    out.append("};\n")
    with open(OUT, "w", newline="\n") as f:
        f.write("".join(out))
    print("%s: %d codepoints, %d bytes" % (OUT, len(cps), len(data)))


if __name__ == "__main__":
    main()
